export const getFormattedDate = (): string => {
  const months = [
    "जनवरी", "फरवरी", "मार्च", "अप्रैल", "मई", "जून",
    "जुलाई", "अगस्त", "सितंबर", "अक्टूबर", "नवंबर", "दिसंबर"
  ];
  
  const today = new Date();
  return `${today.getDate()} ${months[today.getMonth()]}, ${today.getFullYear()}`;
};
